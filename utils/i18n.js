// 标题由页面按内容设置的页面（目录名、产品名等）：进入时先给一个当前语言的通用标题，页面随后会用自己的标题覆盖。
// 不放进 NAV_TITLE，否则每次 onShow 都会把页面设置的标题冲掉
const DEFAULT_TITLE = {
  'pages/catalog/index': 'nav.catalog',
  'pages/product/list': 'nav.list',
  'pages/product/detail': 'nav.detail',
  'pages/order/list': 'nav.orders'
};

const TAB_KEYS = ['tab.home', 'tab.search', 'tab.about', 'tab.mine'];

function detectLang() {
  try {
    const saved = uni.getStorageSync(STORAGE_KEY);
    if (SUPPORTED.includes(saved)) return saved;
  } catch (e) {}
  try {
    const sys = getSystemLanguage().toLowerCase();
    if (sys) return sys.startsWith('zh') ? 'zh' : 'en';
  } catch (e) {}
  return 'zh';
}

// 响应式状态：模板里调用 $t 会依赖 state.lang，切换后自动刷新
const state = Vue.observable({ lang: detectLang() });

export const getLang = () => state.lang;

export function t(key, params) {
  const dict = messages[state.lang] || messages.zh;
  let text = dict[key] !== undefined ? dict[key] : (messages.zh[key] !== undefined ? messages.zh[key] : key);
  if (params) {
    Object.keys(params).forEach((k) => {
      text = text.split('{' + k + '}').join(params[k]);
    });
  }
  return text;
}

// 当前页面的本地化标题（没有登记的页面返回空串）
export function getPageTitle() {
  try {
    const pages = getCurrentPages();
    const current = pages[pages.length - 1];
    const key = current && NAV_TITLE[current.route];
    return key ? t(key) : '';
  } catch (e) {
    return '';
  }
}

// 页面刚加载时先设好当前语言的导航栏标题。
// pages.json 里的标题只能写死一种语言，而原生导航栏在页面渲染前就显示了，
// 所以 pages.json 里留空，这里在 onLoad（早于首次显示）立即补上，避免默认英文时先闪一下中文。
export function applyTitleOnLoad() {
  try {
    const pages = getCurrentPages();
    const current = pages[pages.length - 1];
    const key = current && (NAV_TITLE[current.route] || DEFAULT_TITLE[current.route]);
    if (key) uni.setNavigationBarTitle({ title: t(key) });
  } catch (e) {}
}

// 同步原生部分：tabBar 文字、当前页导航栏标题（这两处不是 Vue 模板，不会自动刷新）
export function applyChrome() {
  TAB_KEYS.forEach((key, index) => {
    uni.setTabBarItem({ index, text: t(key), fail() {} });
  });
  try {
    const pages = getCurrentPages();
    const current = pages[pages.length - 1];
    const titleKey = current && NAV_TITLE[current.route];
    if (titleKey) uni.setNavigationBarTitle({ title: t(titleKey) });
  } catch (e) {}
}

export function setLang(lang) {
  if (!SUPPORTED.includes(lang) || lang === state.lang) return;
  state.lang = lang;
  try {
    uni.setStorageSync(STORAGE_KEY, lang);
  } catch (e) {}
  applyChrome();
}

export default { t, getLang, setLang, applyChrome, applyTitleOnLoad, getPageTitle };
